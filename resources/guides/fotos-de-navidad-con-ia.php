<h2 id="parecido">Cuando no te pareces a ti</h2>

<p>Es la queja más común: la foto es preciosa, pero la persona tiene otra nariz, otra edad o una sonrisa que nunca has puesto. Lo que mejor funciona:</p>

<ol>
    <li><strong>Cambia una cosa cada vez</strong>. Primero el fondo; cuando esté bien, la ropa; luego la luz. Cada vez que pides muchos cambios a la vez, la IA rehace más partes de la imagen, cara incluida.</li>
    <li><strong>Dilo explícitamente en cada mensaje</strong>: «mantén la cara exactamente igual que en la foto original». En conversaciones largas el asistente tiende a olvidarlo.</li>
    <li><strong>Si se ha alejado mucho, vuelve a empezar</strong> con la foto original en una conversación nueva, en vez de corregir la versión ya deformada.</li>
    <li><strong>Evita pedir que te rejuvenezca o «mejore»</strong>: es exactamente la instrucción que le da permiso para cambiarte la cara.</li>
