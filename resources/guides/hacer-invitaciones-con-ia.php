    <li><strong>Los datos, grandes y con contraste</strong>. Mucha gente leerá la invitación en el móvil con el brillo bajo.</li>
    <li><strong>Revisa la fecha con el calendario delante</strong>. «Sábado 14» cuando el 14 es domingo es el error más común en cualquier invitación, la haga una IA o una persona.</li>
</ul>

