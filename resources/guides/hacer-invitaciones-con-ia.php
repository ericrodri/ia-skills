<h2 id="montar">Montar la tarjeta</h2>

<p>Con la ilustración y el texto listos, júntalos en un editor sencillo. Canva es lo más cómodo: tiene plantillas de invitación en los tamaños de móvil e imprenta, y basta con cambiar el fondo por tu ilustración y pegar el texto. Tres reglas:</p>

<ul>
