<p>Si el recorte sale mal, cambiar de web rara vez lo arregla. Lo que más ayuda es hacer mejor la foto:</p>

<ol>
    <li><strong>Contraste</strong>: sujeto claro sobre fondo oscuro o al revés. Una camiseta blanca contra una pared blanca es el peor caso.</li>
