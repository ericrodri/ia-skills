<h2 id="bordes">Pelo, transparencias y bordes difíciles</h2>

<p>Cuando el recorte deja un halo o se come parte del sujeto, prueba esto en orden:</p>

<ul>
    <li><strong>Ajuste manual</strong>: casi todas las herramientas tienen un pincel de «restaurar» y otro de «borrar». Dos o tres pasadas por el borde arreglan la mayoría de los fallos.</li>
    <li><strong>Suavizar o desplazar el borde</strong>: en editores como Photopea, Photoshop o Affinity, contraer la máscara uno o dos píxeles elimina el halo del fondo antiguo.</li>
