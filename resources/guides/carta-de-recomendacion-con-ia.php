<h2 id="peticion">Cómo pedírsela a la IA</h2>

<blockquote>«Redacta una carta de recomendación [laboral/académica] en español. Quien recomienda: [CARGO], que ha sido [relación] de la persona recomendada durante [TIEMPO]. Opta a: [PUESTO/PROGRAMA]; te pego la oferta debajo. Ejemplos que deben aparecer: [EJEMPLO 1], [EJEMPLO 2]. Usa solo estos hechos, no inventes logros ni cifras. Tono profesional y cercano, sin adjetivos vacíos como "proactivo" o "polivalente" si no van con un ejemplo. Máximo una página. Deja huecos entre corchetes para nombres, fecha y contacto.»</blockquote>

<p>La frase «no inventes logros ni cifras» es imprescindible. Sin ella, el modelo tiende a rellenar con méritos plausibles que nadie ha mencionado, y una carta de recomendación con datos falsos puede perjudicar tanto a quien la firma como a quien la presenta.</p>

<p>Después, repasa:</p>

<ul>
    <li>Que cada afirmación la pueda sostener quien firma si le llaman para confirmarla.</li>
    <li>Que no haya frases que valgan para cualquier persona. Si las hay, cámbialas por un hecho o bórralas.</li>
    <li>Que el nombre del puesto y de la empresa o universidad sean los correctos. Las cartas reutilizadas con el nombre equivocado son un clásico.</li>
</ul>

<h2 id="borrador">Si te piden que la escribas tú</h2>

<p>Es muy habitual: pides la carta a un antiguo jefe y te responde «escríbela tú y yo la reviso». En ese caso:</p>

<ol>
    <li>Prepara el borrador con la petición anterior, escrito desde el punto de vista de quien firma.</li>
    <li>Sé moderado con los elogios: es más creíble y es más fácil que te la firmen sin cambios.</li>
    <li>Envíaselo en un formato editable con un correo breve que explique para qué es y el plazo. Si te cuesta redactar ese correo, la guía de <a href="/guias/escribir-correos-con-ia">escribir correos con IA</a> tiene ejemplos.</li>
    <li>Acepta sus cambios. La carta es suya: tiene que poder defenderla.</li>
</ol>

