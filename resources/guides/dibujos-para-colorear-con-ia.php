<h2 id="imprimir">Cómo imprimirlo bien</h2>

<ul>
    <li><strong>Formato</strong>: pide formato vertical. Si sale cuadrado, en la impresión deja márgenes blancos arriba y abajo; no pasa nada.</li>
    <li><strong>Resolución</strong>: descarga la imagen en el tamaño más grande disponible. Si se ve pixelada en A4, pide que la genere de nuevo «en alta resolución» o usa un ampliador de imágenes.</li>
    <li><strong>Grises</strong>: si la impresora saca un fondo grisáceo, abre la imagen en cualquier editor y sube el contraste o conviértela a blanco y negro puro.</li>
    <li><strong>Cuadernillo</strong>: pega las láminas en un documento de texto, una por página, y expórtalo en PDF. Así lo imprimes de una vez o lo llevas a la copistería.</li>
</ul>

