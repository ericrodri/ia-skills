<h2 id="seguimiento">Llevar el control</h2>

<p>Con varias candidaturas abiertas es fácil olvidar a quién respondiste. Pide a la IA una hoja de cálculo sencilla:</p>

<blockquote>«Crea una tabla para seguir mi búsqueda de empleo con estas columnas: empresa, puesto, enlace, fecha de envío, contacto, estado (enviada, entrevista, oferta, descartada), próxima acción y fecha de la próxima acción.»</blockquote>

<p>Una vez por semana, pega la tabla y pide: «¿A qué candidaturas debería hacer seguimiento y qué les escribo?». Si no hay respuesta en dos semanas, un mensaje corto y educado es razonable; más de dos, no.</p>

