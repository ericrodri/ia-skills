<ul>
    <li>Empieza por el párrafo que tengas más claro, no necesariamente por la introducción.</li>
    <li>Una idea por párrafo, con un ejemplo concreto.</li>
    <li>Usa conectores variados para unir ideas: «además», «sin embargo», «por eso», «en cambio».</li>
    <li>Deja la conclusión para el final y que no repita la introducción con otras palabras.</li>
</ul>

<h2 id="corregir">Corregir con la IA</h2>

<p>Aquí es donde más se aprende. Pásale tu texto y pídele correcciones explicadas:</p>

