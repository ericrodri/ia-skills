<h2 id="esquema">Hacer el esquema</h2>

<p>Con las ideas apuntadas, pide ayuda para ordenarlas, no para redactarlas:</p>

<blockquote>«Estas son mis ideas para la redacción. Ayúdame a ordenarlas en un esquema de introducción, desarrollo en [NÚMERO] párrafos y conclusión. Usa mis palabras, no añadas ideas nuevas, y dime si alguna sobra o se repite.»</blockquote>

<p>Un buen esquema es la mitad de una buena redacción. Si te cuesta ver la estructura de un tema, en <a href="/guias/mapas-mentales-y-esquemas-con-ia">mapas mentales y esquemas con IA</a> hay más formas de organizarlo.</p>

