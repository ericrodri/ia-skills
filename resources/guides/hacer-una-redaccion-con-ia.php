<h2 id="ideas">Buscar ideas</h2>

<p>El bloqueo delante de la hoja en blanco es el momento en que más ayuda la IA, siempre que le pidas preguntas y no respuestas:</p>

<blockquote>«Estoy en [CURSO] y tengo que hacer una redacción de [EXTENSIÓN] sobre [TEMA]. No la escribas. Hazme de una en una cinco preguntas que me ayuden a encontrar qué pienso yo sobre el tema y qué ejemplos de mi vida podría usar. Espera a que conteste cada una.»</blockquote>

