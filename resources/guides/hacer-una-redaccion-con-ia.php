<p>Hay un motivo práctico y otro de fondo. El práctico: un texto escrito por la IA se suele notar. Usa palabras que un alumno de tu edad no usa, repite estructuras muy reconocibles y su opinión es tan equilibrada que no dice nada. En <a href="/guias/se-nota-si-un-texto-lo-escribe-una-ia">si se nota que un texto lo escribe una IA</a> repasamos las señales que buscan los profesores.</p>

