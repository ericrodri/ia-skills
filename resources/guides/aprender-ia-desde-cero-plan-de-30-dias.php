<p>Señal de que la semana ha ido bien: tienes tres instrucciones guardadas y las usas sin pensarlo.</p>

<h2 id="semana-3">Semana 3: documentos, datos y verificación</h2>

<p>Objetivo: la parte que separa ahorrar tiempo de generárselo a otro.</p>

<ul>
    <li><strong>Día 1.</strong> <a href="/guias/resumir-documentos-largos-con-ia">Resume un documento largo</a> del que conozcas el contenido. Busca qué se ha dejado fuera: ahí está la lección.</li>
    <li><strong>Día 2.</strong> Pídele algo verificable —una cifra, una norma, una fecha— y compruébalo contra la fuente. Que aparezca inventado no es mala suerte, es <a href="/guias/alucinaciones-de-la-ia">cómo funcionan</a>.</li>
    <li><strong>Día 3.</strong> Trabaja sobre una hoja de cálculo tuya siguiendo <a href="/guias/ia-en-excel-y-google-sheets">la guía de Excel y Google Sheets</a>.</li>
