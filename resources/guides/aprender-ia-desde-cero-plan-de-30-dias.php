<h2 id="semana-1">Semana 1: una tarea, todos los días</h2>

<p>Objetivo: que dejes de mirar la pantalla en blanco.</p>

<p>Elige <strong>la tarea más aburrida de tu semana</strong>. No la más importante: la más aburrida. Cumple las tres condiciones que hacen fácil aprender —se repite, reconoces un buen resultado de un vistazo y equivocarse no cuesta nada.</p>

<ul>
    <li><strong>Día 1–2.</strong> Haz esa tarea con IA y también a tu manera. Compara. El objetivo no es ahorrar tiempo todavía, es ver dónde acierta y dónde se queda corta.</li>
    <li><strong>Día 3–4.</strong> Repítela añadiendo contexto: quién eres, para quién es, qué tono, qué longitud, qué no debe aparecer. Verás el salto. La estructura completa está en <a href="/guias/como-escribir-prompts-efectivos">cómo escribir prompts efectivos</a>.</li>
    <li><strong>Día 5.</strong> Añade un ejemplo de algo tuyo que quedó bien. Un ejemplo suele valer más que tres párrafos de explicación.</li>
    <li><strong>Fin de semana.</strong> Lee <a href="/guias/que-tareas-de-tu-profesion-automatiza-la-ia">qué tareas de tu profesión automatiza la IA</a> y apunta tres candidatas para la semana siguiente.</li>
