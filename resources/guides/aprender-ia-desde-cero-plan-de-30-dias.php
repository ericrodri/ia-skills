    <li><strong>Día 5.</strong> Escribe tu propia lista de «esto sí / esto no». Media página. Es el entregable más valioso del mes.</li>
</ul>

<p>Señal de que la semana ha ido bien: has pillado al modelo equivocándose al menos una vez y sabes cómo lo pillaste.</p>

<h2 id="semana-4">Semana 4: encadenar y medir</h2>

<p>Objetivo: pasar de tareas sueltas a algo que se sostiene solo.</p>

<ul>
    <li><strong>Día 1–2.</strong> Encadena dos pasos que hoy haces seguidos —notas de la llamada a propuesta, incidencia a respuesta— dentro de una sola instrucción guardada.</li>
    <li><strong>Día 3.</strong> Si hay una tarea que repites igual veinte veces al mes, mira si toca <a href="/guias/automatizar-sin-programar-n8n-make-zapier">automatizarla sin programar</a>. Si lo que falta es una herramienta que no existe, <a href="/guias/crear-tu-herramienta-con-ia-sin-programar">puedes construirla tú</a>.</li>
    <li><strong>Día 4.</strong> <a href="/guias/medir-si-la-ia-ahorra-tiempo">Mide</a>. Cronometra una tarea antes y después. Sin número, lo que tienes es una sensación.</li>
    <li><strong>Día 5.</strong> Enséñaselo a alguien. Explicarlo destapa lo que creías saber, y es además la mejor forma de que el equipo lo adopte.</li>
</ul>

<h2 id="despues">Qué viene después, y qué no hace falta</h2>

<p>Terminado el mes, hay tres direcciones razonables y una trampa:</p>

<ul>
    <li><strong>Profundizar en tu oficio.</strong> Los <a href="/guias/prompts-de-ia-por-profesion">prompts por profesión</a> y el catálogo cubren casos que ya no son genéricos.</li>
    <li><strong>Subir un escalón de herramienta.</strong> Agentes que trabajan sobre tus archivos, como <a href="/guias/empezar-con-claude-code">Claude Code</a>, o los <a href="/guias/agentes-de-escritorio-cowork-chatgpt-work">agentes de escritorio</a>.</li>
    <li><strong>Ocuparte del marco.</strong> Si en tu organización no hay reglas, <a href="/guias/politica-de-uso-de-ia-en-la-empresa">escribirlas</a> es más valioso que cualquier truco.</li>
</ul>

<p>La trampa es coleccionar herramientas. Cada semana sale algo nuevo y probarlo todo da sensación de progreso sin producirlo. Quien saca partido de verdad usa dos o tres cosas muy bien, no quince regular.</p>

<h2 id="empresa">Si tienes que formar a un equipo</h2>

<p>Además de por utilidad, hay un motivo legal. El <strong>artículo 4 del Reglamento europeo de IA</strong> obliga desde febrero de 2025 a garantizar un nivel suficiente de alfabetización en IA entre quienes usan estos sistemas en nombre de la organización. No fija umbral de tamaño ni exige un título concreto: pide medidas razonables, proporcionadas al riesgo, y que puedas demostrar que existen. El detalle está en <a href="/guias/ai-act-obligaciones-empresas">la guía del AI Act</a>.</p>

<p>Lo que funciona en equipos pequeños, por experiencia repetida:</p>

<ol>
    <li><strong>Una sesión corta por área, con las tareas de esa área.</strong> La formación genérica se olvida; la que usa el correo real del departamento, no.</li>
    <li><strong>Una lista de herramientas aprobadas, publicada.</strong> Sin ella, la gente usa cuentas personales y ahí sí hay un problema.</li>
    <li><strong>Un sitio común donde se guarden los prompts que funcionan.</strong> Es lo que convierte el aprendizaje individual en capacidad de la empresa.</li>
    <li><strong>Registro de quién se formó y cuándo.</strong> Una hoja basta. Es la parte que te pedirán si alguna vez hay que demostrarlo.</li>
    <li><strong>Repetición cada seis meses.</strong> Las herramientas cambian lo suficiente como para que una formación de hace un año esté desfasada en la mitad de sus ejemplos.</li>
</ol>

<p>Y la regla que ahorra más discusiones: <strong>forma primero a quien ya lo está usando por su cuenta</strong>. En toda organización hay dos o tres personas que llevan meses haciéndolo, normalmente sin contarlo. Convertirlos en referencia interna cuesta cero y funciona mejor que cualquier proveedor externo.</p>
