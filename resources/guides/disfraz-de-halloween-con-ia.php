<h2 id="grupo">Disfraces de pareja, familia y grupo</h2>

<p>Los disfraces de grupo funcionan cuando todos comparten un tema y cada persona tiene un papel reconocible. La IA es buena repartiendo esos papeles:</p>

<blockquote>«Somos cinco amigos, dos de ellos muy altos. Proponme 5 temas para un disfraz de grupo de Halloween en el que cada uno tenga un personaje distinto pero se entienda que vamos juntos. Para cada tema, reparte los papeles teniendo en cuenta la altura.»</blockquote>

<p>Para parejas, pide combinaciones que se entiendan juntas pero también por separado, por si uno se va antes de la fiesta. Y si queréis una imagen del grupo disfrazado para la invitación, puedes generarla con un estilo de ilustración en lugar de usar fotos reales, como explicamos en <a href="/guias/crear-un-avatar-con-ia">crear un avatar con IA</a>.</p>

<h2 id="casero">De la imagen a la lista de materiales</h2>

<p>Este es el paso que más tiempo ahorra. Con la imagen o la descripción final, pide:</p>

<ul>
    <li><strong>Lista de piezas</strong>, separando lo que ya tienes de lo que hay que comprar.</li>
    <li><strong>Alternativa barata</strong> para cada pieza: cartón en lugar de plástico, fieltro en lugar de tela, pintura acrílica en lugar de spray.</li>
    <li><strong>Pasos en orden</strong>, con lo que tiene que secar primero al principio.</li>
    <li><strong>Tiempo estimado</strong> por paso, para saber si cabe en una tarde.</li>
</ul>

<blockquote>«Con esta imagen como referencia, hazme una lista de materiales para construir el disfraz en casa con menos de 15 euros. Tengo cartón, cinta americana, pegamento caliente y ropa negra. Ordena los pasos para terminarlo en 3 horas y dime qué partes son las más frágiles.»</blockquote>

<p>Desconfía de las cantidades exactas y de los precios: la IA los aproxima. Si te recomienda un producto concreto, compruébalo en la tienda antes de dar nada por hecho.</p>

<h2 id="maquillaje">Maquillaje y peinado paso a paso</h2>

