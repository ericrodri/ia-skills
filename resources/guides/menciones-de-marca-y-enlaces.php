<h2 id="medir">Cómo medir las menciones sin comprar nada</h2>

<p>Según el índice de visibilidad en IA que Semrush publicó en 2026 —construido sobre 126 millones de consultas a asistentes entre enero y abril—, el 45 % de los responsables de marketing reconoce que no sabe medir su visibilidad en respuestas generadas, y solo un 9 % dice tener herramientas para seguir todas las métricas. Es decir: casi todo el mercado está tomando decisiones a ciegas en esto. Un seguimiento básico y hecho a mano ya te pone por delante de la mayoría.</p>

<p>Lo mínimo que funciona, en una hoja de cálculo y una hora al trimestre:</p>

<ol>
    <li><strong>Un conjunto fijo de veinte consultas</strong> de tu categoría, escritas como las escribiría un cliente. Las mismas siempre, o no hay serie temporal.</li>
    <li><strong>Lanzarlas en dos o tres asistentes</strong> y anotar tres cosas: si te mencionan, si te citan con URL y qué competidores salen.</li>
    <li><strong>Una alerta por tu nombre de marca</strong> para contar menciones nuevas al mes. Con avisos gratuitos y una búsqueda periódica se cubre lo esencial.</li>
    <li><strong>El volumen de búsqueda de tu marca</strong>, en Search Console filtrando las consultas que contienen tu nombre. Es la señal número tres del estudio y la tienes gratis.</li>
</ol>

<p>Del lado del tráfico, separar las visitas que llegan de asistentes tiene su propia mecánica, y está en la <a href="/guias/medir-el-trafico-de-ia">guía de medición del tráfico de IA</a>.</p>

<p>Un apunte del mismo informe que merece atención de quien organiza el equipo: entre las organizaciones que llevan SEO y visibilidad en IA como un solo flujo de trabajo, un 81 % declaró más tráfico o más contactos desde plataformas de IA, frente a un 36 % de las que lo gestionan por separado. Es una encuesta declarativa, con todo lo que eso implica, pero apunta en la dirección esperable: montar un equipo paralelo de «GEO» suele producir dos estrategias que se estorban.</p>

<h2 id="errores">Lo que no funciona</h2>

<ul>
    <li><strong>Comprar menciones en granjas de listados.</strong> Es el equivalente 2026 de comprar enlaces en directorios: barato, rápido, y reconocible como patrón.</li>
    <li><strong>Publicar notas de prensa sin noticia.</strong> Se replican en sitios que nadie lee y que nadie recupera. Mucho volumen, ninguna señal.</li>
    <li><strong>Pedir a un asistente que «recuerde» tu marca.</strong> No hay nada que recordar entre sesiones, y lo que escribes en un chat no entra en el índice de nadie.</li>
    <li><strong>Medir con capturas sueltas.</strong> Las respuestas varían entre ejecuciones; una comprobación aislada no dice nada. Series o nada.</li>
    <li><strong>Reescribir toda la web en formato pregunta-respuesta.</strong> Ayuda en páginas donde hay preguntas reales. Aplicado a todo, produce un sitio ilegible que además no responde mejor.</li>
</ul>

