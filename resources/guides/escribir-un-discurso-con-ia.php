<p>Pedir primero el orden es el paso que más mejora el resultado: corregir cinco líneas es fácil, corregir tres páginas no. Cuando el orden te convenza, pide el borrador. Después, reescribe tú las frases que no dirías nunca. Si una frase no te imaginas diciéndola en voz alta, fuera. Por qué esos tics delatan el texto lo explicamos en <a href="/guias/se-nota-si-un-texto-lo-escribe-una-ia">se nota si un texto lo escribe una IA</a>.</p>

<h2 id="para-el-oido">Escribir para decirlo en voz alta</h2>

<p>Un discurso no se lee, se escucha, y eso cambia las reglas. Pide a la IA que revise el texto con estas indicaciones:</p>

<ul>
    <li><strong>Frases cortas</strong>, que se puedan decir sin tomar aire a mitad.</li>
    <li><strong>Nada de paréntesis ni incisos largos</strong>: en voz alta se pierden.</li>
    <li><strong>Repite la idea principal</strong> al principio y al final. En un texto escrito sobraría; en un discurso ayuda.</li>
    <li><strong>Marca las pausas</strong> después de las frases que deben hacer efecto, sobre todo antes del remate de un chiste.</li>
    <li><strong>Ajusta la duración</strong>: a un ritmo tranquilo se dicen unas 130 palabras por minuto. Pide que recorte hasta la cifra que necesitas.</li>
</ul>

<p>Para escucharlo antes de decirlo, una herramienta de <a href="/guias/convertir-texto-a-voz-con-ia">texto a voz</a> te deja oír dónde se atasca el texto, aunque el ritmo final será el tuyo.</p>

<h2 id="ensayar">Ensayar con la IA</h2>

<p>Los asistentes con modo de voz, como ChatGPT, Gemini o Copilot en el móvil, sirven de público de ensayo:</p>

<ol>
    <li>Lee el discurso en voz alta al asistente y pide que te diga qué partes le han parecido confusas.</li>
    <li>Pide que te haga de público difícil en un discurso de trabajo: «hazme las tres preguntas más incómodas que me podrían hacer después».</li>
    <li>Convierte el texto en una ficha de apoyo: «resume el discurso en siete palabras clave, una por idea, para llevarlas en una tarjeta».</li>
</ol>

<p>El ensayo de verdad sigue siendo delante de una persona y con cronómetro. La IA no nota si hablas demasiado rápido por los nervios.</p>

