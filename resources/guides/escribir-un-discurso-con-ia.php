<h2 id="por-que-suena-falso">Por qué suena a plantilla</h2>

<p>Si pides «un discurso para la boda de mi hermana», el modelo no conoce a tu hermana. Tiene la estructura media de miles de discursos de boda, y eso es lo que devuelve: saludo, elogio genérico, cita sobre el amor, brindis. Correcto y olvidable. El problema no se arregla pidiendo «más emotivo» o «más gracioso»; se arregla dándole material que solo tienes tú.</p>

