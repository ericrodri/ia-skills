<h2 id="limites">Qué limita la versión gratuita</h2>

<p>Las versiones gratuitas no suelen quitar funciones enteras. Limitan tres cosas:</p>

<ol>
    <li><strong>Cantidad.</strong> Un número de mensajes, imágenes o archivos por día o por franja de horas. Cuando lo agotas, esperas o pasas a un modelo más sencillo.</li>
    <li><strong>Modelo.</strong> El modelo más potente, el que razona más despacio y mejor, suele estar reservado a los planes de pago o muy limitado en el gratuito.</li>
    <li><strong>Tamaño.</strong> Menos documentos por conversación, archivos más pequeños y conversaciones más cortas antes de que el asistente <a href="/guias/ventana-de-contexto-conversaciones-largas">pierda el hilo</a>.</li>
</ol>

<p>Para una persona que usa la IA unas cuantas veces al día, la versión gratuita suele bastar. Se queda corta cuando trabajas con documentos largos, haces muchas iteraciones seguidas o necesitas el mejor modelo para tareas difíciles.</p>

