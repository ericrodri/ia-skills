<h2 id="atajo">El atajo Alt + Espacio: un conflicto que conviene conocer</h2>

<p>En Windows, ChatGPT y Gemini usan el mismo atajo para su ventana rápida, Alt + Espacio, que además es una combinación que Windows y algunos lanzadores de programas ya usan. Si instalas las dos, la que se abrió primero se queda con el atajo y la otra no responde.</p>

<p>La solución es cambiarlo en los ajustes de una de ellas. En ChatGPT está en los ajustes de la aplicación, en el apartado de la ventana rápida. Elige una combinación que no uses para otra cosa, como Ctrl + Alt + Espacio, y así cada asistente tiene la suya.</p>

