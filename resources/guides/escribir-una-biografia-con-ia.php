<h2 id="entrevista">La entrevista, con la IA de guionista</h2>

<p>Lo más valioso de una biografía familiar es la voz de la persona. La IA es muy buena preparando la entrevista:</p>

<blockquote>«Voy a entrevistar a mi abuela, nacida en [AÑO] en [LUGAR], que trabajó de [OFICIO]. Prepárame un guion de preguntas abiertas por etapas: infancia, juventud, trabajo, familia y vejez. Incluye preguntas sobre objetos, olores, canciones y lugares concretos, que despiertan más recuerdos que las preguntas generales. Nada que se pueda contestar con sí o no.»</blockquote>

<p>Graba la conversación con permiso, mejor en varias sesiones cortas que en una larga. Después pasa el audio a texto con las herramientas de <a href="/guias/pasar-audio-a-texto-con-ia">pasar audio a texto con IA</a> y dáselo a la IA con este encargo: «Saca de esta transcripción una cronología con fechas, lugares y personas. Marca con un interrogante todo lo que sea dudoso y dime qué preguntas haría en la siguiente entrevista».</p>

<h2 id="redactar">Ordenar y redactar</h2>

<p>Con la cronología revisada, pide primero la estructura y después el texto, capítulo a capítulo:</p>

<blockquote>«Con esta cronología y estas transcripciones, propón un índice para una biografía de unas 20 páginas. Después redacta el primer capítulo en tercera persona, con un tono cálido y sencillo. Usa frases literales de la entrevista entre comillas cuando sean expresivas. No añadas ningún hecho que no esté en el material.»</blockquote>

<p>La última frase del prompt es la importante. Los asistentes tienden a rellenar con contexto histórico genérico («en aquellos años de penuria…») o con detalles que suenan bien. Lee cada capítulo buscando eso y quítalo. Si el proyecto crece hasta un libro, la guía de <a href="/guias/escribir-un-libro-con-ia">escribir un libro con IA</a> explica cómo mantener el estilo y la coherencia en textos largos.</p>

<p>Y antes de imprimir, pásaselo a la persona o a la familia. Siempre hay alguna fecha mal o un nombre que alguien prefiere no ver por escrito.</p>

