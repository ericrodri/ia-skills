<h2 id="tipos">Tres biografías distintas</h2>

<p>La regla que vale para todas: <strong>la IA no conoce a la persona</strong>, solo lo que le cuentas. Si es alguien conocido, sabe cosas, pero mezcla datos y se equivoca con fechas. Si es alguien de tu familia, no sabe nada y, si le pides una biografía igualmente, se la inventa. Es el fallo que explicamos en <a href="/guias/alucinaciones-de-la-ia">las alucinaciones de la IA</a>. Por eso el trabajo se reparte así: tú pones los hechos, ella ayuda a obtenerlos, ordenarlos y contarlos bien.</p>

