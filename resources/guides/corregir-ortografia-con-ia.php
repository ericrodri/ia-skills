<h2 id="fallos">Lo que la IA corrige mal</h2>

<p>Conviene conocer sus manías para no dar por buena cualquier corrección:</p>

<ul>
    <li><strong>Mayúsculas al estilo inglés</strong> en títulos: «Cómo Corregir Un Texto». En español solo lleva mayúscula la primera palabra y los nombres propios.</li>
    <li><strong>Comillas inglesas</strong> donde preferirías las latinas («»), o al revés.</li>
    <li><strong>Normas desactualizadas</strong>: a veces pone tilde en «solo» o en los demostrativos, que hoy la RAE no exige.</li>
    <li><strong>Extranjerismos y términos de tu sector</strong> que «traduce» o cambia por sinónimos que no significan lo mismo.</li>
